#!/usr/bin/env python3
"""How well the duck follows the phone's sticks (engine.Duck.set_stick), with no phone and no server: the engine is
stepped directly. Each axis alone at 25-100 % deflection, then all three together. 6 s per case from a reset; the
velocity is the mean of the engine's own filtered trunk velocity over the last 4 s. Speed level 3, seed fixed.

    ~/.venvs/microduck_live/bin/python ios/tools/bench_stick.py
    -> docs/figures/duck_ios_stick.pdf, docs/duck_ios_stick_table.tex
"""
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "app"))
import engine  # noqa: E402

LEVEL, T, TAIL = 3, 6.0, 4.0
lv = engine.LEVELS[LEVEL - 1]
VY = min(engine.WALK_VY_MAX, 0.7 * lv["walk"])
duck = engine.Duck({}, lag=4, vin=7.7, sag_gain=0.1, auto_reset=False, walk_self_recovery=True, lively=False, react=False, anim_seed=1)
duck.level = LEVEL


def run(x, y, w):
    """-> commanded (vx, vy, wz), measured (vx, vy, wz), falls."""
    duck.reset()
    f0 = duck.falls
    for _ in range(int(1.0 / duck.control_dt)):
        duck.step()
    duck.set_stick(x, y, w)
    n, keep = int(T / duck.control_dt), int(TAIL / duck.control_dt)
    rec = []
    for i in range(n):
        duck.step()
        if i >= n - keep:
            s = duck.snapshot()
            rec.append((s["v"][0], s["v"][1], s["wz"]))
    duck.set_stick(0, 0, 0)
    cmd = (y * (lv["walk"] if y > 0 else min(0.4, lv["walk"])), -x * VY, -w * lv["yaw"])
    return cmd, tuple(np.mean(rec, axis=0)), duck.falls - f0


F = [0.25, 0.5, 0.75, 1.0]
axes = [("forward", lambda f: (0, f, 0), 0, "m/s"), ("backward", lambda f: (0, -f, 0), 0, "m/s"),
        ("sidestep right", lambda f: (f, 0, 0), 1, "m/s"), ("turn clockwise", lambda f: (0, 0, f), 2, "rad/s")]
fig, ax = plt.subplots(1, 2, figsize=(7.4, 3.1))
rows, falls = [], 0
print(f"{'case':<16}{'stick':>6}{'cmd':>8}{'meas':>8}")
for name, mk, k, unit in axes:
    cmd, meas = [], []
    for f in F:
        c, m, fl = run(*mk(f))
        falls += fl
        cmd.append(abs(c[k])); meas.append(abs(m[k]))
        print(f"{name:<16}{f:>6.2f}{c[k]:>8.3f}{m[k]:>8.3f}")
        rows.append(rf"{name} & {f:.2f} & {c[k]:.2f} & {m[k]:.2f} & {unit} \\")
    a = ax[1] if k == 2 else ax[0]
    a.plot(cmd, meas, "o-", label=name)
for a, u in zip(ax, ("m/s", "rad/s")):
    hi = max(a.get_xlim()[1], a.get_ylim()[1])
    a.plot([0, hi], [0, hi], "k--", lw=.8, alpha=.5)
    a.set_xlabel(f"commanded [{u}]"); a.set_ylabel(f"measured [{u}]"); a.grid(alpha=.25); a.legend(frameon=False, fontsize=8)
fig.tight_layout()
fig.savefig(ROOT / "docs/figures/duck_ios_stick.pdf")
c, m, fl = run(0.5, 0.6, 0.5)                     # both sticks at once: forward-right while turning clockwise
falls += fl
print("combined  cmd (vx, vy, wz) = %.2f %.2f %.2f   measured %.2f %.2f %.2f   falls in all cases: %d" % (*c, *m, falls))
(ROOT / "docs/duck_ios_stick_table.tex").write_text(
    "% generated by ios/tools/bench_stick.py\n\\newcommand{\\iosStick}{" + "\n".join(rows) + "}\n"
    + "\\newcommand{\\iosCombo}{(%.2f, %.2f, %.2f) commanded, (%.2f, %.2f, %.2f) measured}\n" % (*c, *m)
    + "\\newcommand{\\iosStickFalls}{%d}\n" % falls)
